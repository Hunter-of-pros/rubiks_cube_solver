#!/usr/bin/env python3
"""Plot benchmark comparisons across Rubik's Cube solver algorithms.

Reads measured CSV metrics generated by `cpp/build/benchmark_solvers` and
produces publication-quality plots:
  - solver_runtime_vs_depth.png
  - solver_nodes_vs_depth.png
  - solver_moves_vs_depth.png
  - solver_summary_dashboard.png
"""

from __future__ import annotations

import argparse
import csv
from collections import defaultdict
from pathlib import Path
from typing import Dict, List, Tuple

import matplotlib.pyplot as plt
import numpy as np


STYLE_CONFIG = {
    "ida-base": {
        "label": "IDA* (Baseline Heuristic)",
        "color": "#e63946",
        "marker": "o",
        "linestyle": "--",
        "linewidth": 2.0,
    },
    "ida-pdb": {
        "label": "IDA* + Pattern Databases (PDB)",
        "color": "#2a9d8f",
        "marker": "s",
        "linestyle": "-",
        "linewidth": 2.2,
    },
    "kociemba": {
        "label": "Kociemba Two-Phase (Sub-optimal)",
        "color": "#457b9d",
        "marker": "^",
        "linestyle": "-.",
        "linewidth": 2.0,
    },
}


def load_benchmark_data(csv_path: Path) -> Dict[str, Dict[int, Dict[str, Tuple[float, float]]]]:
    """Parse benchmark CSV and compute mean & standard deviation per (algo, depth)."""
    raw_data = defaultdict(lambda: defaultdict(lambda: defaultdict(list)))

    with open(csv_path, "r", encoding="utf-8") as f:
        reader = csv.DictReader(f)
        for row in reader:
            if not row or "algorithm" not in row:
                continue
            algo = row["algorithm"].strip()
            depth = int(row["scramble_depth"])
            raw_data[algo][depth]["elapsed_ms"].append(float(row["elapsed_ms"]))
            raw_data[algo][depth]["nodes"].append(float(row["nodes_expanded"]))
            raw_data[algo][depth]["moves"].append(float(row["solution_length"]))

    stats = defaultdict(lambda: defaultdict(dict))
    for algo, depths in raw_data.items():
        for d, metrics in depths.items():
            for m_name, vals in metrics.items():
                mean = float(np.mean(vals))
                std = float(np.std(vals))
                stats[algo][d][m_name] = (mean, std)

    return stats


def setup_plot_style() -> None:
    """Set clean matplotlib styling."""
    plt.rcParams.update({
        "font.family": "sans-serif",
        "font.size": 11,
        "axes.edgecolor": "#cccccc",
        "axes.linewidth": 1.0,
        "grid.color": "#e5e5e5",
        "grid.linestyle": ":",
        "grid.linewidth": 0.8,
    })


def plot_runtime(stats: dict, out_path: Path) -> None:
    """Plot average runtime (ms) vs scramble depth on a logarithmic scale."""
    fig, ax = plt.subplots(figsize=(8, 5.5), dpi=300)

    for algo, cfg in STYLE_CONFIG.items():
        if algo not in stats:
            continue
        depths = sorted(stats[algo].keys())
        means = [stats[algo][d]["elapsed_ms"][0] for d in depths]
        stds = [stats[algo][d]["elapsed_ms"][1] for d in depths]

        ax.errorbar(
            depths,
            means,
            yerr=stds,
            label=cfg["label"],
            color=cfg["color"],
            marker=cfg["marker"],
            linestyle=cfg["linestyle"],
            linewidth=cfg["linewidth"],
            capsize=4,
            capthick=1.2,
        )

    ax.set_yscale("log")
    ax.set_xlabel("Scramble Depth (Half-Turn Metric)", fontweight="bold")
    ax.set_ylabel("Execution Time (ms, log scale)", fontweight="bold")
    ax.set_title("Solver Runtime vs. Scramble Depth", fontsize=13, fontweight="bold", pad=12)
    ax.grid(True, which="both", alpha=0.7)
    ax.legend(frameon=True, facecolor="white", edgecolor="#cccccc", fontsize=10)

    plt.tight_layout()
    fig.savefig(out_path)
    plt.close(fig)


