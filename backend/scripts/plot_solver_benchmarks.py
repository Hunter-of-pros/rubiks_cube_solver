def plot_moves(stats: dict, out_path: Path) -> None:
    """Plot solution length vs scramble depth, highlighting optimal vs sub-optimal."""
    fig, ax = plt.subplots(figsize=(8, 5.5), dpi=300)

    all_depths = sorted({d for a in stats for d in stats[a]})
    max_d = max(all_depths) if all_depths else 20
    ax.plot([0, max_d], [0, max_d], color="#999999", linestyle=":", linewidth=1.5, label="Optimal Baseline (y = x)")

    for algo, cfg in STYLE_CONFIG.items():
        if algo not in stats:
            continue
        depths = sorted(stats[algo].keys())
        means = [stats[algo][d]["moves"][0] for d in depths]

        ax.plot(
            depths,
            means,
            label=cfg["label"],
            color=cfg["color"],
            marker=cfg["marker"],
            linestyle=cfg["linestyle"],
            linewidth=cfg["linewidth"],
        )

    ax.set_xlabel("Scramble Depth (Half-Turn Metric)", fontweight="bold")
    ax.set_ylabel("Solution Length (Moves HTM)", fontweight="bold")
    ax.set_title("Solution Quality vs. Scramble Depth", fontsize=13, fontweight="bold", pad=12)
    ax.set_ylim(bottom=0)
    ax.grid(True, alpha=0.7)
    ax.legend(frameon=True, facecolor="white", edgecolor="#cccccc", fontsize=10)

    plt.tight_layout()
    fig.savefig(out_path)
    plt.close(fig)


def plot_summary_dashboard(stats: dict, out_path: Path) -> None:
    """Create a 3-panel dashboard summarizing runtime, pruning, and solution length."""
    fig, (ax1, ax2, ax3) = plt.subplots(1, 3, figsize=(18, 5.5), dpi=300)

    # 1. Runtime
    for algo, cfg in STYLE_CONFIG.items():
        if algo not in stats:
            continue
        depths = sorted(stats[algo].keys())
        means = [stats[algo][d]["elapsed_ms"][0] for d in depths]
        ax1.plot(depths, means, label=cfg["label"], color=cfg["color"], marker=cfg["marker"],
                 linestyle=cfg["linestyle"], linewidth=2.0)
    ax1.set_yscale("log")
    ax1.set_xlabel("Scramble Depth", fontweight="bold")
    ax1.set_ylabel("Runtime (ms, log)", fontweight="bold")
    ax1.set_title("Runtime Comparison", fontweight="bold")
    ax1.grid(True, which="both", alpha=0.7)

    # 2. Nodes
    for algo, cfg in STYLE_CONFIG.items():
        if algo not in stats:
            continue
        depths = sorted(stats[algo].keys())
        means = [stats[algo][d]["nodes"][0] for d in depths]
        ax2.plot(depths, means, label=cfg["label"], color=cfg["color"], marker=cfg["marker"],
                 linestyle=cfg["linestyle"], linewidth=2.0)
    ax2.set_yscale("log")
    ax2.set_xlabel("Scramble Depth", fontweight="bold")
    ax2.set_ylabel("Nodes Expanded (log)", fontweight="bold")
    ax2.set_title("Search Tree Pruning", fontweight="bold")
    ax2.grid(True, which="both", alpha=0.7)

    # 3. Moves
    all_depths = sorted({d for a in stats for d in stats[a]})
    max_d = max(all_depths) if all_depths else 20
    ax3.plot([0, max_d], [0, max_d], color="#999999", linestyle=":", linewidth=1.5, label="Optimal (y=x)")
    for algo, cfg in STYLE_CONFIG.items():
        if algo not in stats:
            continue
        depths = sorted(stats[algo].keys())
        means = [stats[algo][d]["moves"][0] for d in depths]
        ax3.plot(depths, means, label=cfg["label"], color=cfg["color"], marker=cfg["marker"],
                 linestyle=cfg["linestyle"], linewidth=2.0)
    ax3.set_xlabel("Scramble Depth", fontweight="bold")
    ax3.set_ylabel("Solution Length (HTM)", fontweight="bold")
    ax3.set_title("Solution Length vs Depth", fontweight="bold")
    ax3.set_ylim(bottom=0)
    ax3.grid(True, alpha=0.7)

    handles, labels = ax1.get_legend_handles_labels()
    fig.legend(handles, labels, loc="upper center", bbox_to_anchor=(0.5, 1.05),
               ncol=3, frameon=True, facecolor="white", edgecolor="#cccccc", fontsize=11)

    plt.tight_layout()
    fig.subplots_adjust(top=0.88)
    fig.savefig(out_path, bbox_inches="tight")
    plt.close(fig)


def main() -> None:
    parser = argparse.ArgumentParser(description="Plot Rubik's Cube solver benchmark comparisons.")
    parser.add_argument(
        "--csv",
        type=Path,
        default=Path("experiments/solver_benchmarks/solver_comparison.csv"),
        help="Path to input benchmark CSV file.",
    )
    parser.add_argument(
        "--out-dir",
        type=Path,
        default=Path("experiments/solver_benchmarks"),
        help="Directory to save generated plots.",
    )
    args = parser.parse_args()

    if not args.csv.exists():
        raise FileNotFoundError(f"Benchmark CSV not found at: {args.csv}")

    args.out_dir.mkdir(parents=True, exist_ok=True)
    setup_plot_style()

    print(f"Loading benchmark metrics from: {args.csv}")
    stats = load_benchmark_data(args.csv)

    print("Generating individual and dashboard plots...")
    plot_runtime(stats, args.out_dir / "solver_runtime_vs_depth.png")
    plot_nodes(stats, args.out_dir / "solver_nodes_vs_depth.png")
    plot_moves(stats, args.out_dir / "solver_moves_vs_depth.png")
    plot_summary_dashboard(stats, args.out_dir / "solver_summary_dashboard.png")

    print(f"Successfully generated 4 benchmark plots in {args.out_dir}:")
    print(f"  - {args.out_dir / 'solver_runtime_vs_depth.png'}")
    print(f"  - {args.out_dir / 'solver_nodes_vs_depth.png'}")
    print(f"  - {args.out_dir / 'solver_moves_vs_depth.png'}")
    print(f"  - {args.out_dir / 'solver_summary_dashboard.png'}")


if __name__ == "__main__":
    main()
